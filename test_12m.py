import time
import os
import warnings
warnings.filterwarnings("ignore")

import yfinance as yf
import pandas as pd
import pandas_ta as ta
from stable_baselines3 import PPO
from stable_baselines3.common.vec_env import DummyVecEnv, VecNormalize
from stable_baselines3.common.monitor import Monitor
from sortino_reward_env import SortinoStocksEnv

checkpoint_path = './checkpoints/ppo_sortino_12000000_steps.zip'
print(f"Waiting for {checkpoint_path} to be generated by the training thread...")

# Block and wait for the file to be fully written
while not os.path.exists(checkpoint_path):
    time.sleep(30)
time.sleep(5) # Give it 5 extra seconds to finish writing to disk

print(f"\n[12 MILLION STEP BRAIN DETECTED] Loading {checkpoint_path}...")

print("--- Fetching Test Market Data ---")
df = yf.download("^NSEI", start="2015-01-01", end="2024-01-01", progress=False)
if df.empty:
    df = yf.download("RELIANCE.NS", start="2015-01-01", end="2024-01-01", progress=False)
if isinstance(df.columns, pd.MultiIndex): 
    df.columns = [c[0] for c in df.columns]

df.ta.sma(length=20, append=True)
df.ta.rsi(length=14, append=True)
df.ta.macd(append=True)
df.ta.bbands(append=True)
df.ta.atr(append=True)
df.dropna(inplace=True)

def make_test_env():
    env = SortinoStocksEnv(
        df=df,
        window_size=30,
        frame_bound=(1500, len(df)),
        reward_mode="differential",
        eta=0.02, trade_fee=0.002, reward_scale=0.05, lambda_dd=1.0, l_floor=2.5e-5, augment_observation=True,
    )
    return Monitor(env)

venv_test = DummyVecEnv([make_test_env])
venv_test = VecNormalize(venv_test, norm_obs=True, norm_reward=False, clip_obs=10.0)
venv_test.training = False 
venv_test.reward_update = False

model = PPO.load(checkpoint_path, env=venv_test, device="cuda")

obs = venv_test.reset()
print("\n--- Running 12M Step Out-of-Sample Backtest ---")
while True:
    action, _states = model.predict(obs, deterministic=True)
    obs, rewards, dones, infos = venv_test.step(action)
    if dones[0]:
        info = infos[0]
        print("\n=====================================")
        print("12 MILLION STEP EXAM RESULTS:")
        print("=====================================")
        print(f"AI Sortino Ratio Achieved: {info.get('terminal_sortino', 0.0)}")
        print("=====================================")
        break
