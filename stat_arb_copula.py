class Signal(int, Enum):
    SHORT_SPREAD = -1     
    FLAT = 0
    LONG_SPREAD = +1      


@dataclass
class SignalSeries:
    signal: np.ndarray            
    h_u_given_v: np.ndarray
    h_v_given_u: np.ndarray
    u: np.ndarray
    v: np.ndarray
    mispricing_index_u: np.ndarray
    mispricing_index_v: np.ndarray
    threshold: float
    confirmed: bool

    @property
    def n_long(self) -> int:
        return int(np.sum(self.signal == 1))

    @property
    def n_short(self) -> int:
        return int(np.sum(self.signal == -1))

    @property
    def signal_rate(self) -> float:
        return float(np.mean(self.signal != 0))

    def summary(self) -> str:
        return (
            f"n={self.signal.size}  long={self.n_long}  short={self.n_short}  "
            f"rate={100*self.signal_rate:.2f}%  "
            f"(alpha={self.threshold:.3f}, confirmed={self.confirmed})"
        )


class CopulaSignalGenerator:
    def __init__(
        self,
        copula: ArchimedeanCopula,
        threshold: float = 0.05,
        confirmed: bool = False,
        exit_band: Optional[float] = None,
    ) -> None:
        if not 0.0 < threshold < 0.5:
            raise ValueError("threshold must lie in (0, 0.5)")
        self.copula = copula
        self.threshold = float(threshold)
        self.confirmed = bool(confirmed)
        self.exit_band = exit_band

    def generate(self, u: np.ndarray, v: np.ndarray) -> SignalSeries:
        u = np.asarray(u, dtype=float).ravel()
        v = np.asarray(v, dtype=float).ravel()
        if u.shape != v.shape:
            raise ValueError("u and v must align")

        h1 = self.copula.h(u, v)
        h2 = self.copula.h_given_u(v, u)
        a = self.threshold

        long_ = h1 < a
        short_ = h1 > 1.0 - a
        if self.confirmed:
            long_ &= h2 > 1.0 - a
            short_ &= h2 < a

        sig = np.zeros(u.size, dtype=np.int8)
        sig[long_] = 1
        sig[short_] = -1

        if self.exit_band is not None:
            sig = self._apply_state_machine(sig, h1)

        return SignalSeries(
            signal=sig, h_u_given_v=h1, h_v_given_u=h2, u=u, v=v,
            mispricing_index_u=np.cumsum(h1 - 0.5),
            mispricing_index_v=np.cumsum(h2 - 0.5),
            threshold=a, confirmed=self.confirmed,
        )

    def _apply_state_machine(self, entry: np.ndarray, h1: np.ndarray) -> np.ndarray:
        b = float(self.exit_band)
        out = np.zeros_like(entry)
        state = 0
        for i in range(entry.size):
            if state == 0:
                state = int(entry[i])
            elif abs(h1[i] - 0.5) <= b:
                state = 0
            out[i] = state
        return out


def _test_end_to_end_with_lognormal_margins() -> None:
    n, theta = 6000, 4.0
    S = ClaytonCopula(theta).sample(n, seed=77)
    x = stats.lognorm(s=0.8).ppf(S[:, 0]) - 1.0
    y = stats.t(df=3).ppf(S[:, 1]) * 0.02

    split = int(0.6 * n)
    mx, my = MarginalTransform().fit(x[:split]), MarginalTransform().fit(y[:split])
    u_tr, v_tr = mx.transform(x[:split]), my.transform(y[:split])

    best, fits = select_copula(u_tr, v_tr)
    
    u_te, v_te = mx.transform(x[split:]), my.transform(y[split:])
    sig = CopulaSignalGenerator(best.copula, 0.05, confirmed=False).generate(u_te, v_te)

    print("--- MODEL CALIBRATION ---")
    print("     " + "\n     ".join(f.summary() for f in fits.values()))
    lam = empirical_tail_dependence(u_tr, v_tr, q=0.05)
    
    print("\n--- PERFORMANCE & DIAGNOSTICS ---")
    print(f"-> Recovered theta: {best.theta:.3f} (True: {theta})")
    print(f"-> Empirical Tails: Lower={lam[0]:.3f}, Upper={lam[1]:.3f}")
    print(f"-> Selected Best Model: {best.copula.name.upper()} (via AIC)")
    
    print("\n--- OUT-OF-SAMPLE SIGNALS ---")
    print(f"-> Evaluated {sig.signal.size} ticks.")
    print(f"-> Trades fired: {sig.n_long + sig.n_short} ({sig.n_long} Longs, {sig.n_short} Shorts)")
