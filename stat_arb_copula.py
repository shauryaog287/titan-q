"""
stat_arb_copula.py
==================

Phase 13: Statistical arbitrage via Archimedean copulas.

    X, Y  ->  pseudo-observations U, V  ->  C(u, v; theta)  ->  h(u | v)  ->  signal

An Archimedean copula is generated by phi: [0,1] -> [0, inf], convex and
decreasing with phi(1) = 0:

    C(u, v) = phi^{-1}( phi(u) + phi(v) )

    Clayton   phi(t) = ( t^{-theta} - 1 ) / theta ,    theta > 0
              C(u,v) = ( u^-theta + v^-theta - 1 )^{-1/theta}
              lambda_L = 2^{-1/theta},  lambda_U = 0

    Gumbel    phi(t) = ( -ln t )^theta ,               theta >= 1
              C(u,v) = exp( -[ (-ln u)^theta + (-ln v)^theta ]^{1/theta} )
              lambda_U = 2 - 2^{1/theta},  lambda_L = 0

The two are not interchangeable: Clayton concentrates dependence in the JOINT
LOWER tail and Gumbel in the JOINT UPPER tail, and each is asymptotically
INDEPENDENT in the other tail. Fitting Gumbel to a pair that crashes together
prices the crash as independent.
"""

