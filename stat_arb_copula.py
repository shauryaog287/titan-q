def pseudo_observations(x: np.ndarray, ties: str = "average") -> np.ndarray:
    x = np.asarray(x, dtype=float).ravel()
    if x.size < 2:
        raise ValueError("need at least 2 observations")
    if not np.all(np.isfinite(x)):
        raise ValueError("x contains non-finite values")
    n = x.size
    r = stats.rankdata(x, method=ties)
    return r / (n + 1.0)


@dataclass
class MarginalTransform:
    _sorted: Optional[np.ndarray] = None
    _n: int = 0
    _fitted: bool = False

    def fit(self, x: np.ndarray) -> "MarginalTransform":
        x = np.asarray(x, dtype=float).ravel()
        if x.size < 2:
            raise ValueError("need at least 2 observations")
        self._sorted = np.sort(x)
        self._n = x.size
        self._fitted = True
        return self

    def transform(self, x: np.ndarray) -> np.ndarray:
        if not self._fitted:
            raise RuntimeError("fit the marginal on a training window first")
        x = np.atleast_1d(np.asarray(x, dtype=float))
        n = self._n
        lo = np.searchsorted(self._sorted, x, side="left")
        hi = np.searchsorted(self._sorted, x, side="right")
        r = 0.5 * (lo + hi)
        u = r / (n + 1.0)
        return np.clip(u, 1.0 / (n + 1.0), n / (n + 1.0))

    def fit_transform(self, x: np.ndarray) -> np.ndarray:
        return self.fit(x).transform(x)


