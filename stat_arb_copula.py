@dataclass
class CopulaFit:
    copula: ArchimedeanCopula
    theta: float
    log_likelihood: float
    n_obs: int
    theta_moment: float
    kendall_tau: float
    std_error: float
    converged: bool

    @property
    def aic(self) -> float:
        return 2.0 * 1 - 2.0 * self.log_likelihood

    @property
    def bic(self) -> float:
        return math.log(self.n_obs) - 2.0 * self.log_likelihood

    def summary(self) -> str:
        lo, up = self.copula.tail_dependence()
        return (
            f"{self.copula.name:<8s} theta={self.theta:8.4f} (moment "
            f"{self.theta_moment:7.4f})  ll={self.log_likelihood:10.3f}  "
            f"AIC={self.aic:10.3f}  tau={self.kendall_tau:+.4f}  "
            f"lam_L={lo:.4f} lam_U={up:.4f}"
        )


def fit_copula_mle(
    family: Literal["clayton", "gumbel"],
    u: np.ndarray,
    v: np.ndarray,
    use_moment_seed: bool = True,
) -> CopulaFit:
    cls = _FAMILIES[family]
    u = np.asarray(u, dtype=float).ravel()
    v = np.asarray(v, dtype=float).ravel()
    if u.shape != v.shape:
        raise ValueError("u and v must align")
    if u.size < 10:
        raise ValueError(f"need >=10 observations, got {u.size}")

    tau = float(stats.kendalltau(u, v).statistic)
    theta_moment = float(np.clip(cls.tau_to_theta(tau), *cls.theta_bounds))

    def neg_ll(th: float) -> float:
        try:
            ll = cls(float(np.clip(th, *cls.theta_bounds))).log_likelihood(u, v)
        except (ValueError, FloatingPointError):
            return 1e12
        return 1e12 if not np.isfinite(ll) else -ll

    lo, hi = cls.theta_bounds
    res = optimize.minimize_scalar(neg_ll, bounds=(lo, hi), method="bounded",
                                   options={"xatol": 1e-10, "maxiter": 500})
    theta_hat = float(np.clip(res.x, lo, hi))

    if use_moment_seed and neg_ll(theta_moment) < neg_ll(theta_hat):
        theta_hat = theta_moment

    step = max(1e-5, 1e-4 * abs(theta_hat))
    a, b, c = neg_ll(theta_hat - step), neg_ll(theta_hat), neg_ll(theta_hat + step)
    curv = (a - 2.0 * b + c) / step**2
    se = float(1.0 / math.sqrt(curv)) if curv > 0 else float("nan")

    cop = cls(theta_hat)
    return CopulaFit(
        copula=cop, theta=theta_hat, log_likelihood=cop.log_likelihood(u, v),
        n_obs=u.size, theta_moment=theta_moment, kendall_tau=tau,
        std_error=se, converged=bool(res.success),
    )


def select_copula(
    u: np.ndarray, v: np.ndarray,
    families: Sequence[str] = ("clayton", "gumbel"),
    criterion: Literal["aic", "bic", "loglik"] = "aic",
) -> Tuple[CopulaFit, Dict[str, CopulaFit]]:
    fits = {f: fit_copula_mle(f, u, v) for f in families}
    key = {"aic": lambda f: f.aic, "bic": lambda f: f.bic,
           "loglik": lambda f: -f.log_likelihood}[criterion]
    return fits[min(fits, key=lambda f: key(fits[f]))], fits


def tail_dependence_at_q(cop: "ArchimedeanCopula", q: float) -> Tuple[float, float]:
    q = float(q)
    one = np.array([1.0 - q])
    qq = np.array([q])
    c_ll = float(cop.cdf(qq, qq)[0])
    c_uu = float(cop.cdf(one, one)[0])
    return c_ll / q, (1.0 - 2.0 * (1.0 - q) + c_uu) / q


def empirical_tail_dependence(
    u: np.ndarray, v: np.ndarray, q: float = 0.05
) -> Tuple[float, float]:
    u = np.asarray(u, dtype=float)
    v = np.asarray(v, dtype=float)
    lo_v, hi_v = v <= q, v > 1.0 - q
    lam_l = float(np.mean(u[lo_v] <= q)) if lo_v.sum() else float("nan")
    lam_u = float(np.mean(u[hi_v] > 1.0 - q)) if hi_v.sum() else float("nan")
    return lam_l, lam_u


