class ArchimedeanCopula:
    name: str = "archimedean"
    theta_bounds: Tuple[float, float] = (-np.inf, np.inf)
    independence_theta: float = 0.0

    def __init__(self, theta: float) -> None:
        lo, hi = self.theta_bounds
        if not (lo <= theta <= hi):
            raise ValueError(f"{self.name}: theta={theta} outside {self.theta_bounds}")
        self.theta = float(theta)

    def cdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        raise NotImplementedError

    def log_pdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        raise NotImplementedError

    def h(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        raise NotImplementedError

    def sample(self, n: int, seed: int = 0) -> np.ndarray:
        raise NotImplementedError

    @staticmethod
    def tau_to_theta(tau: float) -> float:
        raise NotImplementedError

    def theta_to_tau(self) -> float:
        raise NotImplementedError

    def tail_dependence(self) -> Tuple[float, float]:
        raise NotImplementedError

    def pdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        return np.exp(self.log_pdf(u, v))

    def log_likelihood(self, u: np.ndarray, v: np.ndarray) -> float:
        lp = self.log_pdf(u, v)
        if not np.all(np.isfinite(lp)):
            return -np.inf
        return float(np.sum(lp))

    def h_given_u(self, v: np.ndarray, u: np.ndarray) -> np.ndarray:
        return self.h(v, u)

    def h_inverse(self, w: np.ndarray, v: np.ndarray) -> np.ndarray:
        w = np.atleast_1d(np.asarray(w, dtype=float))
        v = np.atleast_1d(np.asarray(v, dtype=float))
        out = np.empty_like(w)
        for i in range(w.size):
            vi = float(v[i] if v.size > 1 else v[0])
            f = lambda uu: float(self.h(np.array([uu]), np.array([vi]))[0]) - float(w[i])
            out[i] = optimize.brentq(f, _U_FLOOR, _U_CEIL, xtol=1e-14, maxiter=200)
        return out

    @staticmethod
    def _clip(u: np.ndarray) -> np.ndarray:
        return np.clip(np.asarray(u, dtype=float), _U_FLOOR, _U_CEIL)

    def __repr__(self) -> str:
        lo, up = self.tail_dependence()
        return (f"{self.name}(theta={self.theta:.4f}, tau={self.theta_to_tau():.4f}, "
                f"lam_L={lo:.4f}, lam_U={up:.4f})")


class ClaytonCopula(ArchimedeanCopula):
    name = "clayton"
    theta_bounds = (1e-6, 60.0)
    independence_theta = 1e-6

    def _log_S(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        t = self.theta
        a = -t * np.log(u)
        b = -t * np.log(v)
        m = np.maximum(a, b)
        return m + np.log(np.exp(a - m) + np.exp(b - m) - np.exp(-m))

    def cdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        return np.exp(-self._log_S(u, v) / self.theta)

    def log_pdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        t = self.theta
        return (
            math.log1p(t)
            - (t + 1.0) * (np.log(u) + np.log(v))
            - (2.0 + 1.0 / t) * self._log_S(u, v)
        )

    def h(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        t = self.theta
        log_h = -(t + 1.0) * np.log(v) - ((1.0 + t) / t) * self._log_S(u, v)
        return np.clip(np.exp(log_h), 0.0, 1.0)

    def h_inverse(self, w: np.ndarray, v: np.ndarray) -> np.ndarray:
        w = self._clip(np.atleast_1d(w))
        v = self._clip(np.atleast_1d(v))
        t = self.theta
        inner = v ** (-t) * (w ** (-t / (1.0 + t)) - 1.0) + 1.0
        return np.clip(inner ** (-1.0 / t), _U_FLOOR, _U_CEIL)

    def sample(self, n: int, seed: int = 0) -> np.ndarray:
        rng = np.random.default_rng(seed)
        v = rng.uniform(_U_FLOOR, _U_CEIL, n)
        w = rng.uniform(_U_FLOOR, _U_CEIL, n)
        return np.column_stack([self.h_inverse(w, v), v])

    @staticmethod
    def tau_to_theta(tau: float) -> float:
        tau = float(np.clip(tau, 1e-6, 0.95))
        return 2.0 * tau / (1.0 - tau)

    def theta_to_tau(self) -> float:
        return self.theta / (self.theta + 2.0)

    def tail_dependence(self) -> Tuple[float, float]:
        return 2.0 ** (-1.0 / self.theta), 0.0


class GumbelCopula(ArchimedeanCopula):
    name = "gumbel"
    theta_bounds = (1.0, 40.0)
    independence_theta = 1.0

    def _log_A(self, x: np.ndarray, y: np.ndarray) -> np.ndarray:
        t = self.theta
        lx, ly = np.log(x), np.log(y)
        return logsumexp(np.stack([t * lx, t * ly]), axis=0) / t

    def cdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        x, y = -np.log(u), -np.log(v)
        return np.exp(-np.exp(self._log_A(x, y)))

    def log_pdf(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        t = self.theta
        x, y = -np.log(u), -np.log(v)
        log_A = self._log_A(x, y)
        A = np.exp(log_A)
        return (
            -A
            + (t - 1.0) * (np.log(x) + np.log(y))
            - (np.log(u) + np.log(v))
            + (1.0 - 2.0 * t) * log_A
            + np.log(A + t - 1.0)
        )

    def h(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        u, v = self._clip(u), self._clip(v)
        t = self.theta
        x, y = -np.log(u), -np.log(v)
        log_A = self._log_A(x, y)
        log_h = -np.exp(log_A) + (t - 1.0) * np.log(y) + (1.0 - t) * log_A - np.log(v)
        return np.clip(np.exp(log_h), 0.0, 1.0)

    def sample(self, n: int, seed: int = 0) -> np.ndarray:
        rng = np.random.default_rng(seed)
        t = self.theta
        if abs(t - 1.0) < 1e-12:
            return rng.uniform(_U_FLOOR, _U_CEIL, (n, 2))

        alpha = 1.0 / t
        th = rng.uniform(_EPS, math.pi - _EPS, n)
        W = rng.exponential(1.0, n)
        S = (
            np.sin(alpha * th) / np.sin(th) ** (1.0 / alpha)
            * (np.sin((1.0 - alpha) * th) / W) ** ((1.0 - alpha) / alpha)
        )
        E = rng.exponential(1.0, (n, 2))
        U = np.exp(-((E / S[:, None]) ** (1.0 / t)))
        return np.clip(U, _U_FLOOR, _U_CEIL)

    @staticmethod
    def tau_to_theta(tau: float) -> float:
        tau = float(np.clip(tau, 0.0, 0.95))
        return 1.0 / (1.0 - tau)

    def theta_to_tau(self) -> float:
        return 1.0 - 1.0 / self.theta

    def tail_dependence(self) -> Tuple[float, float]:
        return 0.0, 2.0 - 2.0 ** (1.0 / self.theta)


_FAMILIES: Dict[str, type] = {"clayton": ClaytonCopula, "gumbel": GumbelCopula}


